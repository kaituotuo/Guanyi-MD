'use strict';

// Run against the local prototype server. Uses an externally supplied browser runtime.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { chromium } = require(process.env.GUANYI_PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.GUANYI_PROTOTYPE_URL || 'http://127.0.0.1:9943/docs/prototypes/home-study/index.html';
const output = process.env.GUANYI_ACCEPTANCE_OUTPUT || fs.mkdtempSync(path.join(os.tmpdir(), 'guanyi-reading-'));
fs.mkdirSync(output, { recursive:true });
const checks = [];
const errors = [];
const pass = label => { checks.push(label); console.log(`PASS ${label}`); };

(async () => {
  const browser = await chromium.launch({ headless:true, ...(process.env.GUANYI_CHROMIUM_EXECUTABLE ? { executablePath:process.env.GUANYI_CHROMIUM_EXECUTABLE } : {}) });
  try {
    const page = await browser.newPage({ viewport:{width:1440,height:1000} });
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base);
    await page.locator('#recent-list .recent-row').first().waitFor();
    assert.equal(await page.locator('#sidebar').isVisible(), true);
    assert.equal(await page.locator('.home-heading').count(), 0);
    assert.equal(await page.locator('.workspace-toolbar').evaluate(element => getComputedStyle(element).backgroundColor), 'rgba(0, 0, 0, 0)');
    assert.equal(await page.locator('.workspace-toolbar').evaluate(element => getComputedStyle(element).borderBottomWidth), '0px');
    assert.equal(await page.locator('.search-bar').evaluate(element => getComputedStyle(element).borderTopWidth), '1px');
    await page.screenshot({path:path.join(output, 'guanyi-home-search.png')});
    await page.setViewportSize({width:760,height:960});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({path:path.join(output, 'guanyi-home-search-narrow.png')});
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('[data-action="open-smart-study"]').click();
    let frame = page.frames().find(item => item.url().includes('/pdf-study/workspace.html'));
    assert.ok(frame, 'PDF workspace loaded from the smart-reading entry');
    await frame.waitForFunction(() => {
      const state = window.__PDF_STUDY_PROTOTYPE__?.getState();
      return state?.document === 'paper' && state.panel === 'guide' && !document.getElementById('study-panel').classList.contains('is-hidden');
    });
    assert.equal(await page.locator('#sidebar').isVisible(), false);
    assert.equal(await frame.locator('#panel-tab-guide').getAttribute('aria-selected'), 'true');
    pass('Home smart-reading entry opens the sample PDF with its guide panel expanded');
    await page.locator('[data-tab="home"]').click();

    await page.locator('#global-search-input').fill('教材示例');
    assert.equal(await page.locator('#recent-list .recent-row').count(), 1);
    assert.equal(await page.locator('#recent-list').textContent().then(text => text.includes('运动生理学')), true);
    await page.locator('#global-search-input').press('Enter');
    assert.equal(await page.locator('#view-caption').textContent(), '运动生理学');
    assert.equal(await page.locator('#sidebar').isVisible(), false);
    await page.locator('[data-tab="home"]').click();
    await page.locator('#global-search-input').fill('');
    await page.locator('#recent-list [data-open-doc="doc-textbook"]').first().click();
    frame = page.frames().find(item => item.url().includes('/pdf-study/workspace.html'));
    assert.ok(frame, 'PDF workspace loaded');
    const pdfState = () => frame.evaluate(() => window.__PDF_STUDY_PROTOTYPE__.getState());
    await frame.waitForFunction(() => window.__PDF_STUDY_PROTOTYPE__?.getState().document === 'textbook' && document.getElementById('study-panel').classList.contains('is-hidden'));
    assert.equal(await page.locator('#sidebar').isVisible(), false);
    assert.equal(await frame.locator('#library').isVisible(), true);
    assert.equal(await frame.locator('.library-document').first().isVisible(), false);
    assert.equal(await frame.locator('#study-panel').isVisible(), false);
    await page.screenshot({path:path.join(output, 'guanyi-reading-light.png')});
    pass('Home opens a document without the folder list; document navigation and paper are visible');

    await frame.locator('#outline [data-page="55"]').click();
    assert.equal((await pdfState()).page, 55);
    await frame.locator('#next-page').click();
    assert.equal((await pdfState()).page, 56);
    await frame.locator('#previous-page').click();
    await frame.locator('#page-input').fill('42');
    await frame.locator('#page-input').press('Enter');
    await frame.waitForFunction(() => window.__PDF_STUDY_PROTOTYPE__.getState().page === 42);
    await frame.locator('#zoom-select').selectOption('1');
    await frame.locator('#library-toggle').click();
    assert.equal(await frame.locator('#library').isVisible(), false);
    await frame.locator('#library-toggle').click();
    assert.equal(await frame.locator('#library').isVisible(), true);
    pass('Outline, page navigation, zoom and navigation collapse remain usable');

    await frame.locator('[data-navigation="bookmarks"]').click();
    await frame.locator('#bookmark-current').click();
    assert.equal(await frame.locator('#document-bookmarks [data-page="42"]').count(), 1);
    await frame.locator('#study-toggle').click();
    assert.equal(await frame.locator('#study-panel').isVisible(), true);
    await page.screenshot({path:path.join(output, 'guanyi-reading-study.png')});
    await frame.locator('#study-close').click();
    assert.equal(await frame.locator('#study-panel').isVisible(), false);
    await page.locator('[data-tab="home"]').click();
    assert.equal(await page.locator('#sidebar').isVisible(), true);
    await page.locator('#recent-list [data-open-doc="doc-research"]').first().click();
    await frame.waitForFunction(() => window.__PDF_STUDY_PROTOTYPE__.getState().document === 'paper');
    await page.locator('[data-tab="doc-textbook"]').click();
    await frame.waitForFunction(() => window.__PDF_STUDY_PROTOTYPE__.getState().document === 'textbook');
    assert.equal((await pdfState()).page, 42);
    pass('AI expands and collapses; Home restores folders; PDF tabs restore their own document and position');

    await page.reload();
    frame = page.frames().find(item => item.url().includes('/pdf-study/workspace.html'));
    await frame.waitForFunction(() => window.__PDF_STUDY_PROTOTYPE__?.getState().document === 'textbook');
    await frame.locator('[data-navigation="bookmarks"]').click();
    assert.equal(await frame.locator('#document-bookmarks [data-page="42"]').count(), 1);
    await frame.locator('#document-bookmarks [data-remove-bookmark="42"]').click();
    assert.equal(await frame.locator('#document-bookmarks [data-page="42"]').count(), 0);
    await frame.locator('[data-navigation="outline"]').click();
    await page.locator('#theme-toggle').click();
    await frame.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
    await page.screenshot({path:path.join(output, 'guanyi-reading-dark.png')});
    pass('Bookmarks survive reload and can be removed; the embedded reading view follows the app theme');

    await page.setViewportSize({width:760,height:960});
    await frame.locator('#study-toggle').click();
    await frame.locator('#library-toggle').click();
    assert.equal(await frame.locator('#library').isVisible(), true);
    assert.equal(await frame.locator('#study-panel').isVisible(), false);
    await frame.locator('#outline [data-page="55"]').click();
    await frame.waitForFunction(() => !document.getElementById('library').classList.contains('is-open'));
    await frame.locator('#study-toggle').click();
    assert.equal(await frame.locator('#library').isVisible(), false);
    assert.equal(await frame.locator('#workspace-scrim').isVisible(), true);
    await page.screenshot({path:path.join(output, 'guanyi-reading-narrow.png')});
    await frame.locator('#workspace-scrim').click({position:{x:5,y:100}});
    assert.equal(await frame.locator('#study-panel').isVisible(), false);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    pass('At 760px document navigation and AI are exclusive drawers; outline navigation and the scrim close them');

    await page.setViewportSize({width:1440,height:1000});
    await page.locator('[data-tab="home"]').click();
    await page.locator('#recent-list [data-open-doc="doc-notes"]').first().click();
    assert.equal(await page.locator('#sidebar').isVisible(), false);
    assert.equal(await page.locator('.text-outline').isVisible(), true);
    assert.equal(await page.locator('#text-view h1').textContent(), '运动生理学阅读笔记');
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.locator('.text-outline').isVisible(), false);
    await page.locator('#text-outline-toggle').click();
    assert.equal(await page.locator('.text-outline').isVisible(), true);
    await page.locator('.text-outline [data-heading="document-heading-0"]').click();
    assert.equal(await page.locator('.text-outline').isVisible(), false);
    assert.equal(await page.locator('#text-outline-toggle').getAttribute('aria-expanded'), 'false');
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('#edit-reading-doc').click();
    assert.equal(await page.locator('#md-source').inputValue(), '# 运动生理学阅读笔记\n\n## 待回答的问题\n\n- 耗氧量与供氧能力有什么区别？\n- 哪些测量条件会影响解释？\n\n> 来源：运动生理学，持续补充你的理解。');
    assert.equal(await page.locator('#sidebar').isVisible(), false);
    await page.locator('#md-source').fill('# 运动生理学阅读笔记\n\n这是一条原型验收笔记。');
    await page.locator('#md-save').click();
    await page.locator('[data-tab="home"]').click();
    await page.locator('#recent-list [data-open-doc="doc-notes"]').first().click();
    assert.match(await page.locator('#text-view').textContent(), /这是一条原型验收笔记/);
    await page.screenshot({path:path.join(output, 'guanyi-reading-markdown.png')});
    pass('Markdown opens in reading view and can switch to editing, save and return to reading');

    await page.locator('[data-tab="home"]').click();
    await page.locator('#recent-list [data-open-doc="doc-ebook"]').first().click();
    assert.equal(await page.locator('#sidebar').isVisible(), false);
    assert.equal(await page.locator('#text-view h1').textContent(), '阅读与学习方法');
    assert.equal(await page.locator('.text-outline nav button').count(), 4);
    assert.match(await page.locator('#text-view').textContent(), /并非真实导入的电子书/);
    pass('EPUB fixture opens the generic reading shell with clearly labeled sample content');

    const direct = await browser.newPage({viewport:{width:1440,height:1000}});
    direct.on('pageerror', error => errors.push(error.message));
    await direct.goto(`${base}?view=doc-textbook`);
    await direct.waitForFunction(() => document.body.dataset.workspace === 'reading');
    assert.equal(await direct.locator('#sidebar').isVisible(), false);
    await direct.close();
    assert.deepEqual(errors, []);
    pass('A direct reading-view link works and the tested paths raise no page errors');
    fs.writeFileSync(path.join(output, 'reading-acceptance.json'), JSON.stringify({checks,errors}, null, 2));
    console.log(`Reading browser acceptance passed (${checks.length} groups). Screenshots: ${output}`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
